#!/usr/bin/env python3
"""Controlled RFCOMM peer on the Android SDK's local Netsim, never real radios.

Host test dependency: bumble[android]==0.0.236 in a separate virtual environment.
No dependency or Python code is packaged in Collie's APK.
"""
import argparse
import asyncio
import json
import logging
import signal
import uuid
from pathlib import Path
from bumble.core import UUID
from bumble.device import Device,DeviceConfiguration
from bumble.rfcomm import Server,make_service_sdp_records
from bumble.transport import open_transport

p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--transport',required=True,help='android-netsim:127.0.0.1:PORT,name=collie-test-UNIQUE')
p.add_argument('--out',type=Path,required=True)
p.add_argument('--uuid',required=True)
p.add_argument('--lifetime',type=int,default=300)
a=p.parse_args()
assert 30 <= a.lifetime <= 1800
assert a.transport.startswith(('android-netsim:127.0.0.1:','android-netsim:localhost:'))
assert ',name=collie-test-' in a.transport
state=dict(bytes_received=0,echoed=False,closed=False,error=None)
def save():
 a.out.parent.mkdir(parents=True,exist_ok=True)
 temporary=a.out.with_suffix('.tmp');temporary.write_text(json.dumps(state,indent=2)+'\n');temporary.replace(a.out)

async def main():
 stop=asyncio.Event();loop=asyncio.get_running_loop()
 for sig in [signal.SIGTERM,signal.SIGINT]:loop.add_signal_handler(sig,stop.set)
 async with await open_transport(a.transport) as transport:
  config=DeviceConfiguration();config.name='Collie RFCOMM test peer '+uuid.uuid4().hex[:8];config.classic_enabled=True;config.le_enabled=False
  device=Device.from_config_with_hci(config,transport.source,transport.sink)
  def connection_opened(connection):
   def encryption_changed():state['encrypted']=connection.is_encrypted;save()
   connection.on(connection.EVENT_CONNECTION_ENCRYPTION_CHANGE,encryption_changed)
  device.on(device.EVENT_CONNECTION,connection_opened)
  server=Server(device)
  def accepted(session):
   state['connected']=True;save()
   def closed():state['closed']=True;save()
   session.on(session.EVENT_CLOSE,closed)
   def received(data):
    at=state['bytes_received']
    if at+len(data)>32768 or any(value!=(at+i)%256 for i,value in enumerate(data)):
     state['error']='RFCOMM payload differs from the independently generated byte oracle';save();return
    state['bytes_received']+=len(data)
    if state['bytes_received']==32768:
     async def echo():
      session.write(bytes(i%256 for i in range(32768)));await session.drain();state['echoed']=True;save()
     asyncio.create_task(echo())
    save()
   session.sink=received
  channel=server.listen(accepted)
  device.sdp_service_records={0x10001:make_service_sdp_records(0x10001,channel,UUID(a.uuid))}
  await device.power_on();await device.set_discoverable(True);await device.set_connectable(True)
  state.update(ready=True,address=str(device.public_address),uuid=a.uuid,name=config.name);save()
  try:await asyncio.wait_for(stop.wait(),a.lifetime)
  except TimeoutError:pass
  state['ready']=False;save()
  await device.power_off()

logging.basicConfig(level=logging.WARNING)
asyncio.run(main())
