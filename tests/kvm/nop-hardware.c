#include <stdint.h>
#include <stdio.h>

#define CHECK(bytes) do { \
    uint64_t a=UINT64_MAX, c=0x8000000000000000ull, d=0x123456789abcdef0ull, flags; \
    __asm__ volatile("pushq $0xad7; popfq; " bytes "; pushfq; popq %3" \
        : "+a"(a), "+c"(c), "+d"(d), "=r"(flags) : : "cc", "memory"); \
    if (a!=UINT64_MAX || c!=0x8000000000000000ull || d!=0x123456789abcdef0ull || (flags&0x8d5)!=0x8d5) return 1; \
} while (0)

int main(void) {
    CHECK(".byte 0x66,0x90");
    CHECK(".byte 0x0f,0x1f,0x00");
    CHECK(".byte 0x0f,0x1f,0x40,0xff");
    CHECK(".byte 0x0f,0x1f,0x44,0x00,0xff");
    CHECK(".byte 0x66,0x0f,0x1f,0x44,0x00,0xff");
    CHECK(".byte 0x0f,0x1f,0x80,0xff,0xff,0xff,0xff");
    CHECK(".byte 0x0f,0x1f,0x84,0x00,0xff,0xff,0xff,0xff");
    CHECK(".byte 0x66,0x0f,0x1f,0x84,0x00,0xff,0xff,0xff,0xff");
    CHECK(".byte 0x66,0x66,0x2e,0x0f,0x1f,0x84,0x00,0,0,0,0");
    CHECK(".byte 0x4f,0x0f,0x1f,0xc0");
    CHECK(".byte 0x41,0x66,0x90");
    CHECK(".rept 14; .byte 0x66; .endr; .byte 0x90");
    puts("PASS: hardware NOP encodings preserve operands and flags without memory access");
    return 0;
}
